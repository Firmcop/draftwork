// Builds packages/core/dist/kernel.mjs: the exact (OpenCascade) kernel as one ES module that runs in Node and in
// browsers. It is made from the same src/ files as the app's engine worker, so the app and the configurator always
// share one kernel. The list of files is read from scripts/build.mjs (const ENGINE = [...]) so it cannot drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const src = f => fs.readFileSync(path.join(root, 'src', f), 'utf8');
const strip = s => s.split('\n').filter(l => !/^import /.test(l)).map(l => l.replace(/^export /, '')).join('\n');

const appBuild = fs.readFileSync(path.join(root, 'scripts/build.mjs'), 'utf8');
const m = /const ENGINE = (\[[^\]]*\]);/.exec(appBuild);
if (!m) throw new Error('packages/core: could not find the ENGINE module list in scripts/build.mjs');
const ENGINE = JSON.parse(m[1].replace(/'/g, '"'));

// Pure helpers that live in UI files: copied by name (the whole function, braces matched).
function sliceFunction(text, name) {
  const start = text.indexOf(`function ${name}(`);
  if (start < 0) throw new Error(`packages/core: function ${name} not found`);
  let i = text.indexOf('{', start), depth = 0;
  for (; i < text.length; i++) {
    const c = text[i];
    if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return text.slice(start, i + 1);
  }
  throw new Error(`packages/core: unbalanced braces in ${name}`);
}
const borrowed = [['sheetui.js', 'dxfOf']].map(([f, n]) => `// ---- ${n} (from src/${f}) ----\n` + sliceFunction(src(f), n)).join('\n');

const code = `// GENERATED by packages/core/build.mjs from src/ — do not edit.
import * as THREE from 'three';
import * as RCmod from 'replicad';
class Brush { } class Evaluator { } const ADDITION = 0, SUBTRACTION = 1, INTERSECTION = 2;   // mesh booleans are not used by the exact kernel
${ENGINE.map(f => `// ---- ${f} ----\n` + strip(src(f + '.js'))).join('\n')}
${borrowed}
function setOC(oc) { RCmod.setOC(oc); RC = RCmod; }
export { setOC, engineHost, evalExpr, evalParams, resolveFeatures, regenerateBrep, brepImportSTEP, importShapes, toBinarySTL, makeZip, dxfOf, RCmod, THREE };
`;

const out = path.join(here, 'dist');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'kernel.mjs'), code);
console.log(`packages/core: dist/kernel.mjs (${ENGINE.length} engine modules, ${(code.length / 1024).toFixed(0)} KB)`);
