# Generates src/font.js: printable-ASCII glyph outlines (flattened, 1000 units per em) from DejaVu Sans.
# DejaVu fonts are under the Bitstream Vera / public-domain style licence, which allows embedding.
import sys, json
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen
path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
f = TTFont(path); gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f['head'].unitsPerEm
S = 1000 / upm
def q(v): return round(v * S)
out = {}
for code in range(32, 127):
    name = cmap.get(code)
    if not name: continue
    pen = DecomposingRecordingPen(gs); gs[name].draw(pen)
    contours, cur, last = [], [], None
    for op, args in pen.value:
        if op == 'moveTo': cur = [args[0]]; last = args[0]
        elif op == 'lineTo': cur.append(args[0]); last = args[0]
        elif op == 'qCurveTo':
            pts = list(args); ctrl = pts[:-1]; end = pts[-1]
            # implied on-curve points between consecutive off-curve points
            segs = []; p0 = last
            for i, c in enumerate(ctrl):
                e = end if i == len(ctrl) - 1 else ((c[0] + ctrl[i+1][0]) / 2, (c[1] + ctrl[i+1][1]) / 2)
                segs.append((p0, c, e)); p0 = e
            for a, c, e in segs:
                n = 4
                for k in range(1, n + 1):
                    t = k / n; u = 1 - t
                    cur.append((u*u*a[0] + 2*u*t*c[0] + t*t*e[0], u*u*a[1] + 2*u*t*c[1] + t*t*e[1]))
            last = end
        elif op == 'curveTo':
            a = last; c1, c2, e = args
            for k in range(1, 7):
                t = k / 6; u = 1 - t
                cur.append((u**3*a[0] + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*e[0], u**3*a[1] + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*e[1]))
            last = e
        elif op in ('closePath', 'endPath'):
            pts = []
            for p in cur:
                qp = (q(p[0]), q(p[1]))
                if not pts or pts[-1] != qp: pts.append(qp)
            if len(pts) > 1 and pts[0] == pts[-1]: pts.pop()
            if len(pts) >= 3: contours.append([v for p in pts for v in p])
            cur = []
    out[chr(code)] = [q(f['hmtx'][name][0]), contours]
js = ('// ===== Built-in sketch text font: printable ASCII outlines from DejaVu Sans (Bitstream Vera licence), 1000 units/em =====\n'
      '// Generated by scripts/mkfont.py. Each glyph: [advance, [contour as flat x,y list, ...]].\n'
      'const GLYPHS = ' + json.dumps(out, separators=(',', ':')) + ';\n'
      '// Closed outlines (sketch units) for a line of text: baseline starts at (x, y), cap height ~ h, rotated by angle (deg).\n'
      'export function textPolys(t) {\n'
      '  const s = (+t.h || 10) / 729, a = (+t.angle || 0) * Math.PI / 180, ca = Math.cos(a), sa = Math.sin(a), polys = [];\n'
      '  let pen = 0; const str = String(t.str ?? \'\');\n'
      '  for (const ch of str) {\n'
      '    const g = GLYPHS[ch] || GLYPHS[\'?\'];\n'
      '    for (const c of g[1]) { const pts = []; for (let i = 0; i < c.length; i += 2) { const lx = (pen + c[i]) * s, ly = c[i + 1] * s; pts.push({ x: +t.x + lx * ca - ly * sa, y: +t.y + lx * sa + ly * ca }); } polys.push(pts); }\n'
      '    pen += g[0] + (+t.spacing || 0) * 10;\n'
      '  }\n'
      '  return { polys, width: pen * s };\n'
      '}\n'
      '// Legacy-style closed profiles for every text item of a sketch (holes come from nesting).\n'
      'export function textProfiles(sk, refs) {\n'
      '  const out = [];\n'
      '  for (const t of sk.texts || []) {\n'
      '    const { polys } = textPolys(t);\n'
      '    if (refs?.length) { const xs = polys.flat(); if (!xs.length) continue; const x0 = Math.min(...xs.map(p => p.x)), x1 = Math.max(...xs.map(p => p.x)), y0 = Math.min(...xs.map(p => p.y)), y1 = Math.max(...xs.map(p => p.y));\n'
      '      if (!refs.some(r => r.text === t.id || (r.x >= x0 && r.x <= x1 && r.y >= y0 && r.y <= y1))) continue; }\n'
      '    polys.forEach((pts, i) => out.push({ id: t.id + \'#\' + i, kind: \'poly\', pts, text: t.id }));\n'
      '  }\n'
      '  return out;\n'
      '}\n')
open(sys.argv[2] if len(sys.argv) > 2 else 'src/font.js', 'w').write(js)
print(len(js), 'bytes')
